-- Links to an archived project can neither be made nor removed directly; the
-- one exception is a cascade (trigger depth > 1) when the reference itself is deleted.
create function app.reference_projects_guard() returns trigger
language plpgsql security definer
set search_path = ''
as $$
begin
  if tg_op = 'INSERT' then
    perform app.assert_project_active(new.project_id);
    return new;
  end if;
  if pg_trigger_depth() = 1 then
    perform app.assert_project_active(old.project_id);
  end if;
  return old;
end
$$;

create function app.reference_projects_log() returns trigger
language plpgsql security definer
set search_path = ''
as $$
declare
  link public.library_reference_projects := case when tg_op = 'DELETE' then old else new end;
  label text;
begin
  select r.title into label from public.library_references r where r.id = link.reference_id;
  -- The reference or the project is going away: library_references_log_delete()
  -- records the first case with the title; nothing to record for the second.
  if label is null or not exists (select 1 from public.projects p where p.id = link.project_id) then
    return null;
  end if;
  perform app.log_project_activity(link.workspace_id, link.project_id,
    case when tg_op = 'DELETE' then 'reference_removed' else 'reference_added' end,
    jsonb_build_object('reference_id', link.reference_id, 'title', label));
  return null;
end
$$;

create function app.library_references_log_delete() returns trigger
language plpgsql security definer
set search_path = ''
as $$
begin
  insert into public.project_activity (workspace_id, project_id, actor_id, kind, data)
  select l.workspace_id, l.project_id, app.current_user_id(), 'reference_removed',
         jsonb_build_object('title', old.title, 'deleted', true)
  from public.library_reference_projects l
  where l.reference_id = old.id;
  return old;
end
$$;

-- Moving a board into or out of a project needs that project to be active.
create function app.moodboards_guard() returns trigger
language plpgsql security definer
set search_path = ''
as $$
begin
  if tg_op = 'INSERT' then
    if new.project_id is not null then
      perform app.assert_project_active(new.project_id);
    end if;
  elsif new.project_id is distinct from old.project_id then
    if old.project_id is not null then
      perform app.assert_project_active(old.project_id);
    end if;
    if new.project_id is not null then
      perform app.assert_project_active(new.project_id);
    end if;
  end if;
  return new;
end
$$;

create function app.moodboards_log() returns trigger
language plpgsql security definer
set search_path = ''
as $$
begin
  if tg_op = 'DELETE' then
    if old.project_id is not null and exists (select 1 from public.projects p where p.id = old.project_id) then
      perform app.log_project_activity(old.workspace_id, old.project_id, 'moodboard_removed',
        jsonb_build_object('title', old.name, 'deleted', true));
    end if;
    return null;
  end if;
  if tg_op = 'UPDATE' and old.project_id is not distinct from new.project_id then
    return null;
  end if;
  if tg_op = 'UPDATE' and old.project_id is not null then
    perform app.log_project_activity(old.workspace_id, old.project_id, 'moodboard_removed',
      jsonb_build_object('moodboard_id', old.id, 'title', new.name));
  end if;
  if new.project_id is not null then
    perform app.log_project_activity(new.workspace_id, new.project_id, 'moodboard_added',
      jsonb_build_object('moodboard_id', new.id, 'title', new.name));
  end if;
  return null;
end
$$;

-- An explicit cover that leaves the collection stops being the cover.
create function app.collection_items_clear_cover() returns trigger
language plpgsql security definer
set search_path = ''
as $$
begin
  update public.library_collections c
     set cover_reference_id = null
   where c.id = old.collection_id and c.cover_reference_id = old.reference_id;
  return null;
end
$$;


-- FRAMEWORK M3: Visual Library.
--
-- Adds image references (metadata only; the bytes live in object storage),
-- a library tag vocabulary, per-user favorites, collections, reference <->
-- project links, and moodboards with their canvas elements. Follows the M1/M2
-- model:
--   * every table has row-level security keyed on app.is_workspace_member();
--   * framework_app gets column-level, least-privilege grants;
--   * children reference parents with composite (id, workspace_id) foreign keys,
--     so nothing can point into another workspace;
--   * project history for references and moodboards is written by triggers.
-- 0001 and 0002 are not edited. The one change to an M2 object is widening the
-- set of kinds `project_activity` accepts.

-- ---------------------------------------------------------------------------
-- References
-- ---------------------------------------------------------------------------

create table public.library_references (
  id uuid primary key default gen_random_uuid(),
  workspace_id uuid not null references public.workspaces (id) on delete cascade,
  title text not null check (char_length(title) between 1 and 200 and title = btrim(title)),
  description text not null default '' check (char_length(description) <= 5000),
  source_url text check (
    source_url is null
    or (char_length(source_url) <= 2048 and source_url ~ '^https?://[^\s]+$')
  ),
  -- Where the files are in object storage: "<storage_key>/original", "/preview", "/thumb".
  -- Generated by the server from ids, never from the uploaded filename.
  storage_key text not null unique check (storage_key ~ '^[a-z0-9/_-]+$' and char_length(storage_key) <= 200),
  original_filename text not null check (char_length(original_filename) between 1 and 255),
  mime_type text not null check (mime_type in ('image/jpeg', 'image/png', 'image/webp', 'image/gif', 'image/avif', 'image/tiff')),
  byte_size bigint not null check (byte_size > 0),
  width integer not null check (width > 0),
  height integer not null check (height > 0),
  sha256 text not null check (sha256 ~ '^[0-9a-f]{64}$'),
  dominant_color text not null default '#1a1d22' check (dominant_color ~ '^#[0-9a-f]{6}$'),
  -- Selected, non-identifying facts about the original (format details, camera, capture date).
  metadata jsonb not null default '{}'::jsonb check (jsonb_typeof(metadata) = 'object'),
  created_by uuid not null references public.auth_users (id),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (id, workspace_id)
);
create index library_references_recent_idx on public.library_references (workspace_id, created_at desc, id desc);
create index library_references_title_idx on public.library_references (workspace_id, lower(title), id);
create index library_references_hash_idx on public.library_references (workspace_id, sha256);

-- ---------------------------------------------------------------------------
-- Tags (a vocabulary separate from project tags: different lifecycles)
-- ---------------------------------------------------------------------------

create table public.library_tags (
  id uuid primary key default gen_random_uuid(),
  workspace_id uuid not null references public.workspaces (id) on delete cascade,
  name text not null check (char_length(name) between 1 and 30 and name = btrim(name) and name !~ '[,\n\r]'),
  created_at timestamptz not null default now(),
  unique (id, workspace_id)
);
create unique index library_tags_name_key on public.library_tags (workspace_id, lower(name));

create table public.library_reference_tags (
  reference_id uuid not null,
  tag_id uuid not null,
  workspace_id uuid not null,
  created_at timestamptz not null default now(),
  primary key (reference_id, tag_id),
  foreign key (reference_id, workspace_id) references public.library_references (id, workspace_id) on delete cascade,
  foreign key (tag_id, workspace_id) references public.library_tags (id, workspace_id) on delete cascade
);
create index library_reference_tags_tag_idx on public.library_reference_tags (tag_id, reference_id);

-- ---------------------------------------------------------------------------
-- Favorites (per person: one member's favorites are not another's)
-- ---------------------------------------------------------------------------

create table public.library_favorites (
  user_id uuid not null references public.auth_users (id) on delete cascade,
  reference_id uuid not null,
  workspace_id uuid not null,
  created_at timestamptz not null default now(),
  primary key (user_id, reference_id),
  foreign key (reference_id, workspace_id) references public.library_references (id, workspace_id) on delete cascade
);
create index library_favorites_reference_idx on public.library_favorites (reference_id);

-- ---------------------------------------------------------------------------
-- Collections
-- ---------------------------------------------------------------------------

create table public.library_collections (
  id uuid primary key default gen_random_uuid(),
  workspace_id uuid not null references public.workspaces (id) on delete cascade,
  name text not null check (char_length(name) between 1 and 80 and name = btrim(name)),
  description text not null default '' check (char_length(description) <= 2000),
  -- An explicit cover. When null, the most recently added item is used.
  cover_reference_id uuid,
  created_by uuid not null references public.auth_users (id),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (id, workspace_id),
  foreign key (cover_reference_id, workspace_id) references public.library_references (id, workspace_id)
    on delete set null (cover_reference_id)
);
create unique index library_collections_name_key on public.library_collections (workspace_id, lower(name));

create table public.library_collection_items (
  collection_id uuid not null,
  reference_id uuid not null,
  workspace_id uuid not null,
  added_at timestamptz not null default now(),
  primary key (collection_id, reference_id),
  foreign key (collection_id, workspace_id) references public.library_collections (id, workspace_id) on delete cascade,
  foreign key (reference_id, workspace_id) references public.library_references (id, workspace_id) on delete cascade
);
create index library_collection_items_reference_idx on public.library_collection_items (reference_id);
create index library_collection_items_recent_idx on public.library_collection_items (collection_id, added_at desc);

-- ---------------------------------------------------------------------------
-- References linked to projects (one reference, many projects; no copies)
-- ---------------------------------------------------------------------------

create table public.library_reference_projects (
  reference_id uuid not null,
  project_id uuid not null,
  workspace_id uuid not null,
  created_at timestamptz not null default now(),
  primary key (reference_id, project_id),
  foreign key (reference_id, workspace_id) references public.library_references (id, workspace_id) on delete cascade,
  foreign key (project_id, workspace_id) references public.projects (id, workspace_id) on delete cascade
);
create index library_reference_projects_project_idx on public.library_reference_projects (project_id, created_at desc);

-- ---------------------------------------------------------------------------
-- Moodboards
-- ---------------------------------------------------------------------------

create table public.moodboards (
  id uuid primary key default gen_random_uuid(),
  workspace_id uuid not null references public.workspaces (id) on delete cascade,
  name text not null check (char_length(name) between 1 and 120 and name = btrim(name)),
  description text not null default '' check (char_length(description) <= 2000),
  project_id uuid,
  background text not null default '#0c0e11' check (background ~ '^#[0-9a-f]{6}$'),
  -- Incremented by every layout save; a save names the version it was based on,
  -- so a stale tab cannot silently overwrite a newer layout.
  version integer not null default 1 check (version > 0),
  created_by uuid not null references public.auth_users (id),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (id, workspace_id),
  foreign key (project_id, workspace_id) references public.projects (id, workspace_id) on delete set null (project_id)
);
create index moodboards_workspace_idx on public.moodboards (workspace_id, updated_at desc, id);
create index moodboards_project_idx on public.moodboards (project_id) where project_id is not null;

-- Element ids are generated by the editor, so a layout save is an idempotent
-- "make the board look like this" that can be retried safely.
create table public.moodboard_elements (
  id uuid primary key,
  moodboard_id uuid not null,
  workspace_id uuid not null,
  kind text not null check (kind in ('image', 'text')),
  reference_id uuid,
  x double precision not null check (abs(x) <= 1000000),
  y double precision not null check (abs(y) <= 1000000),
  width double precision not null check (width > 0 and width <= 100000),
  height double precision not null check (height > 0 and height <= 100000),
  z integer not null,
  text text not null default '' check (char_length(text) <= 5000),
  style jsonb not null default '{}'::jsonb check (jsonb_typeof(style) = 'object'),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  check ((kind = 'image') = (reference_id is not null)),
  check (kind = 'text' or text = ''),
  foreign key (moodboard_id, workspace_id) references public.moodboards (id, workspace_id) on delete cascade,
  -- Deleting a reference removes it from every board (the UI warns first).
  foreign key (reference_id, workspace_id) references public.library_references (id, workspace_id) on delete cascade
);
create index moodboard_elements_board_idx on public.moodboard_elements (moodboard_id, z);
create index moodboard_elements_reference_idx on public.moodboard_elements (reference_id) where reference_id is not null;

